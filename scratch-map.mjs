import { chromium } from "playwright";
const base = process.env.UI_BASE_URL;
const ids = ["availability", "resilience", "usability", "accessibility", "security", "performance", "maintainability"];
const seed = { v: 1, qualities: ids.map((id) => ({ id, priority: null, hidden: false })), custom: [], hiddenItems: [], layers: ["approaches"], showSingles: false, updated: "2026-10-20T00:00:00.000Z" };
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
await page.addInitScript((s) => localStorage.setItem("q42.map.v1", JSON.stringify(s)), seed);
await page.goto(base + "/map/");
const node = page.locator('#map-canvas .map-node[data-type="quality"]').first();
const b = await node.boundingBox();
await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2);
await page.mouse.down();
await page.mouse.move(b.x + 700, b.y + 60, { steps: 10 });
await page.mouse.up();
await page.mouse.move(640, 500);
await page.mouse.wheel(0, 600);
await page.waitForTimeout(800);
const stage = page.locator(".map-controls").first();
await page.locator(".map-controls").scrollIntoViewIfNeeded();
const clip = async (name) => {
  const c = await page.locator(".map-controls").boundingBox();
  const s = await page.locator(".map-stage").boundingBox();
  await page.screenshot({ path: `.scratch-shots/${name}.png`, clip: { x: 0, y: c.y - 10, width: 1280, height: s.y + s.height - c.y + 20 } });
};
await clip("before");
await page.locator("#map-tighten").click();
await page.waitForTimeout(300);
await clip("after");
await browser.close();
